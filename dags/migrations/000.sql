CREATE TABLE public.user_order_log
(
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uniq_id        VARCHAR NOT NULL,
    date_time      TIMESTAMP NOT NULL,
    city_id        BIGINT,
    city_name      VARCHAR,
    customer_id    BIGINT,
    first_name     VARCHAR,
    last_name      VARCHAR,
    item_id        BIGINT,
    item_name      VARCHAR,
    quantity       BIGINT,
    payment_amount NUMERIC(14, 2)
);

CREATE TABLE public.user_activity_log
(
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    uniq_id     VARCHAR NOT NULL,
    date_time   TIMESTAMP NOT NULL,
    action_id   BIGINT,
    customer_id BIGINT,
    quantity    BIGINT
);
